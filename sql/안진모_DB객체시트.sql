-- 회원 잔여 머니 조회 함수(컴파일O,테스트X)
CREATE OR REPLACE FUNCTION FN_GET_USER_MONEY_BALANCE
(
V_USER_ID USERS.USER_ID%TYPE
)
RETURN NUMBER
AS
    RESULT MONEY_TRANSACTION_HISTORY.AMOUNT%TYPE;
    CHARGE_MONEY MONEY_CHARGE_HISTORY.CHARGE_AMOUNT%TYPE;
    MINUS_MONEY MONEY_TRANSACTION_HISTORY.AMOUNT%TYPE;
    PLUS_MONEY MONEY_TRANSACTION_HISTORY.AMOUNT%TYPE;
BEGIN
    RESULT := 0;
    
    SELECT NVL(SUM(CHARGE_AMOUNT),0) INTO CHARGE_MONEY
    FROM MONEY_CHARGE_HISTORY
    WHERE USER_ID = V_USER_ID;
    
    RESULT := RESULT+NUMBER(CHARGE_MONEY);
    
    SELECT NVL(SUM(A.AMOUNT),0) INTO MINUS_MONEY
    FROM MONEY_TRANSACTION_HISTORY A LEFT JOIN MONEY_TYPE B
    ON A.MONEY_TYPE_ID = B.MONEY_TYPE_ID
    WHERE A.USER_ID = V_USER_ID
    AND B.MONEY_TYPE_NAME IN ('결제','판매 보증금 납부','구매 보증금 납부'
    ,'결제 대금 입금');
    
    RESULT := RESULT-MINUS_MONEY;
    
    SELECT NVL(SUM(A.AMOUNT),0) INTO PLUS_MONEY
    FROM MONEY_TRANSACTION_HISTORY A LEFT JOIN MONEY_TYPE B
    ON A.MONEY_TYPE_ID = B.MONEY_TYPE_ID
    WHERE A.USER_ID = V_USER_ID
    AND B.MONEY_TYPE_NAME IN ('판매 보증금 환급','구매 보증금 환급');
    
    RESULT := RESULT+PLUS_MONEY;
    
    RETURN RESULT;
END;


