    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,F.USER_ID,N_MONEY_TYPE_ID1,F.AUCTION_ID,G.AMOUNT
    FROM PURCHASE_CONFIRM_HISTORY A 
    INNER JOIN DELIVERY_COMPLETED C
    ON A.SHIPPING_ID = C.SHIPPING_ID
    INNER JOIN AUCTION_WINNING_PAYMENT D
    ON C.PAYMENT_ID = D.PAYMENT_ID
    INNER JOIN AUCTION_WINNING_RESULT E
    ON D.BID_RESULT_ID = E.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION F
    ON E.BID_ID = F.BID_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY G
    ON F.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID2
    LEFT JOIN MONEY_TRANSACTION_HISTORY H
    ON H.USER_ID = G.USER_ID AND H.AUCTION_ID = G.AUCTION_ID
    AND H.MONEY_TYPE_ID = N_MONEY_TYPE_ID1
    WHERE H.MONEY_ID IS NULL;
    -- GROUP BY F.USER_ID
    
    -- 판매보증금 환급
    INSERT INTO MONEY_TRANSACTION_HISTORY(MONEY_ID,USER_ID,MONEY_TYPE_ID
    ,AUCTION_ID,AMOUNT)
    SELECT MONEY_TRANSACTION_SEQ.NEXTVAL,J.USER_ID,N_MONEY_TYPE_ID1,F.AUCTION_ID,G.AMOUNT
    FROM PURCHASE_CONFIRM_HISTORY A 
    INNER JOIN DELIVERY_COMPLETED C
    ON A.SHIPPING_ID = C.SHIPPING_ID
    INNER JOIN AUCTION_WINNING_PAYMENT D
    ON C.PAYMENT_ID = D.PAYMENT_ID
    INNER JOIN AUCTION_WINNING_RESULT E
    ON D.BID_RESULT_ID = E.BID_RESULT_ID
    INNER JOIN AUCTION_BID_PARTICIPATION F
    ON E.BID_ID = F.BID_ID
    INNER JOIN AUCTION_REGISTRATION I
    ON F.AUCTION_ID = I.AUCTION_ID
    INNER JOIN PRODUCT J
    ON I.PRODUCT_ID = J.PRODUCT_ID
    INNER JOIN MONEY_TRANSACTION_HISTORY G
    ON F.USER_ID = G.USER_ID AND F.AUCTION_ID = G.AUCTION_ID
    AND G.MONEY_TYPE_ID = N_MONEY_TYPE_ID4
    LEFT JOIN MONEY_TRANSACTION_HISTORY H
    ON H.USER_ID = G.USER_ID AND H.AUCTION_ID = G.AUCTION_ID
    AND H.MONEY_TYPE_ID = N_MONEY_TYPE_ID3
    WHERE H.MONEY_ID IS NULL;
    
    COMMIT;
END;

